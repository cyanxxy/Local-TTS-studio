#!/usr/bin/env node
// Pins the browser model files in src/lib/manifests/ to exact Hugging Face
// commits. Every size and SHA-256 comes from the Hugging Face API at the pinned
// revision; files stored without LFS (small JSON) are downloaded, checked
// against their git blob id, and hashed locally.
//
//   node scripts/pin-model-manifests.mjs          check the committed modules
//   node scripts/pin-model-manifests.mjs --write  regenerate them
//
// To move a model to a new revision, change it in MANIFEST_SPECS and run --write.
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const ROOT_DIR = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const HF_HOST = "https://huggingface.co";
const ALLOWED_LICENSES = new Set(["apache-2.0", "mit"]);

const KITTEN_FP32 = { repo: "KittenML/kitten-tts-nano-0.8-fp32", revision: "7a1db645b1f3ab9420761d87428e042b9cec3f26" };
const PARADEE = { repo: "sahilmahendrakar/Paradee-8M-v1.0", revision: "c7f83f86c04e84d0ae94cbe1aad7618e0544f80a" };

export const MANIFEST_SPECS = [
  {
    output: "src/lib/manifests/kitten.ts",
    description: "Kitten TTS Nano 0.8. Only the fp32 export: the int8 one (KittenML/kitten-tts-nano-0.8-int8) is under half the size but runs 1.2-3.5x slower in WASM and not at all on WebGPU.",
    files: [
      { exportName: "KITTEN_NANO_FP32_MODEL", comment: "Standard-op fp32 graph, used on WebGPU and WASM.", ...KITTEN_FP32, path: "kitten_tts_nano_v0_8.onnx" },
      { exportName: "KITTEN_VOICES_FILE", comment: "Eight float32 [400, 256] style tables, stored uncompressed.", ...KITTEN_FP32, path: "voices.npz" },
      { exportName: "KITTEN_CONFIG_FILE", comment: "Voice aliases and per-voice speed priors.", ...KITTEN_FP32, path: "config.json" },
    ],
  },
  {
    output: "src/lib/manifests/paradee.ts",
    description: "Paradee-8M v1.0, a single-voice distillation of Kokoro-82M af_heart.",
    files: [
      { exportName: "PARADEE_INT8_MODEL", comment: "Weight-only int8 graph (DequantizeLinear on initializers).", ...PARADEE, path: "onnx/paradee_int8.onnx" },
      { exportName: "PARADEE_CONFIG_FILE", comment: "Kokoro phoneme vocabulary and sample rate.", ...PARADEE, path: "config.json" },
    ],
  },
];

function formatInteger(value) {
  return String(value).replace(/\B(?=(\d{3})+(?!\d))/g, "_");
}

/** Render one manifest module from resolved file metadata. Pure, so tests can check committed output. */
export function renderManifestModule(spec, resolvedFiles) {
  const lines = [
    "// Generated by scripts/pin-model-manifests.mjs from the Hugging Face API.",
    "// Do not edit by hand: change the revision there and run it with --write.",
    'import type { PinnedModelFile } from "./types";',
    "",
    `// ${spec.description}`,
  ];
  for (const file of spec.files) {
    const resolved = resolvedFiles.get(file.exportName);
    if (!resolved) throw new Error(`Missing metadata for ${file.exportName}.`);
    lines.push(
      "",
      `/** ${file.comment} */`,
      `export const ${file.exportName}: PinnedModelFile = {`,
      `  repo: ${JSON.stringify(file.repo)},`,
      `  revision: ${JSON.stringify(file.revision)},`,
      `  path: ${JSON.stringify(file.path)},`,
      `  byteLength: ${formatInteger(resolved.byteLength)},`,
      `  sha256: ${JSON.stringify(resolved.sha256)},`,
      `  license: ${JSON.stringify(resolved.license)},`,
      "};",
    );
  }
  return `${lines.join("\n")}\n`;
}

async function fetchOk(url) {
  const response = await fetch(url);
  if (!response.ok) throw new Error(`GET ${url} failed: HTTP ${response.status}.`);
  return response;
}

const revisionInfoCache = new Map();

async function revisionInfo(repo, revision) {
  const key = `${repo}@${revision}`;
  if (!revisionInfoCache.has(key)) {
    const url = `${HF_HOST}/api/models/${repo}/revision/${revision}?blobs=true`;
    revisionInfoCache.set(key, fetchOk(url).then((response) => response.json()));
  }
  const info = await revisionInfoCache.get(key);
  if (info.sha !== revision) throw new Error(`${repo} resolved ${revision} to ${info.sha}; pin a full commit SHA.`);
  return info;
}

async function resolveFile(file) {
  const info = await revisionInfo(file.repo, file.revision);
  const license = String(info.cardData?.license ?? "");
  if (!ALLOWED_LICENSES.has(license)) throw new Error(`${file.repo} has license "${license}", which is not allow-listed.`);
  const sibling = info.siblings?.find((entry) => entry.rfilename === file.path);
  if (!sibling || !Number.isSafeInteger(sibling.size)) throw new Error(`${file.repo}@${file.revision} has no ${file.path}.`);
  if (sibling.lfs?.sha256) {
    return { byteLength: sibling.size, sha256: sibling.lfs.sha256, license };
  }

  const url = `${HF_HOST}/${file.repo}/resolve/${file.revision}/${file.path}`;
  const bytes = Buffer.from(await (await fetchOk(url)).arrayBuffer());
  const blobId = createHash("sha1").update(`blob ${bytes.byteLength}\0`).update(bytes).digest("hex");
  if (bytes.byteLength !== sibling.size || blobId !== sibling.blobId) {
    throw new Error(`${file.path} downloaded from ${file.repo} does not match its git blob ${sibling.blobId}.`);
  }
  return { byteLength: bytes.byteLength, sha256: createHash("sha256").update(bytes).digest("hex"), license };
}

async function main() {
  const write = process.argv.includes("--write");
  let stale = 0;
  for (const spec of MANIFEST_SPECS) {
    const resolvedFiles = new Map();
    for (const file of spec.files) resolvedFiles.set(file.exportName, await resolveFile(file));
    const expected = renderManifestModule(spec, resolvedFiles);
    const outputPath = resolve(ROOT_DIR, spec.output);
    let current = null;
    try {
      current = readFileSync(outputPath, "utf8");
    } catch {
      // A missing module is reported as stale below.
    }
    if (current === expected) {
      console.log(`ok       ${spec.output}`);
    } else if (write) {
      writeFileSync(outputPath, expected);
      console.log(`written  ${spec.output}`);
    } else {
      stale += 1;
      console.error(`stale    ${spec.output} (run with --write)`);
    }
  }
  if (stale > 0) process.exitCode = 1;
}

if (process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) {
  await main();
}
