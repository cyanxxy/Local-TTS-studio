type KokoroDtype = "fp32" | "fp16" | "q8";
type KokoroVoiceId = NonNullable<GenerateOptions["voice"]>;

const BACKEND_CONFIG: Readonly<Record<InferenceBackend, { dtype: KokoroDtype; modelFile: string }>> = {
  webgpu: { dtype: "fp32", modelFile: "onnx/model.onnx" },
  wasm: { dtype: "q8", modelFile: "onnx/model_quantized.onnx" },
};
const BACKEND_ORDER: readonly InferenceBackend[] = ["webgpu", "wasm"];
// Exact sizes at KOKORO_MODEL_REVISION, generated by scripts/pin-hf-assets.mjs;
// regenerate the manifest with the revision.
const LOAD_ASSET_SIZES: Readonly<Record<string, PinnedAssetIntegrity>> = KOKORO_LOAD_ASSETS.files;
// A load is abandoned only when it stalls: when no download progress arrives
// for this long, or when the session is still not ready this long after the
// last download finished. A slow but steady download never times out, so a
// slow connection keeps the WebGPU model it is downloading.
const KOKORO_LOAD_INACTIVITY_MS = 60_000;
const KOKORO_LOAD_SETTLING_MS = 120_000;
// Downloads fill the bar up to here; session creation and warm-up take the rest.
const DOWNLOAD_PROGRESS_MAX = 94;
const KOKORO_VOICE_CACHE_NAME = "kokoro-voices";
const KOKORO_VOICE_CACHE_REVISION_MARKER = `https://huggingface.co/${KOKORO_MODEL_ID}/open-tts-cache-revision`;
const KOKORO_TRANSFORMERS_CACHE_NAME = "transformers-cache";
const KOKORO_TRANSFORMERS_CACHE_REVISION_MARKER = `https://huggingface.co/${KOKORO_MODEL_ID}/open-tts-transformers-cache-revision`;

// Kokoro's context: 512 input ids, the "$" start and end tokens included.
// kokoro-js tokenizes with truncation at this length, so a passage whose
// phonemes need more ids would silently lose its end.
const KOKORO_MAX_INPUT_IDS = 512;

type KokoroPhonemize = (text: string, language?: string) => Promise<string>;
type KokoroInputIds = Parameters<KokoroTTSInstance["generate_from_ids"]>[0];
type KokoroTokenize = (text: string, options: { truncation: boolean }) => { input_ids: KokoroInputIds };
type KokoroRawAudio = Awaited<ReturnType<KokoroTTSInstance["generate"]>>;
// kokoro-js keeps its phonemizer private; vite.kokoroAssets.ts re-exports it
// from the kokoro.web.js the worker imports, and fails builds without it.
type KokoroModule = typeof import("kokoro-js") & { phonemize?: KokoroPhonemize };

let tts: KokoroTTSInstance | null = null;
let voices: string[] = [];
let activeBackend: InferenceBackend | null = null;
let phonemize: KokoroPhonemize | null = null;
let kokoroModulePromise: Promise<KokoroModule> | null = null;
const workerRuntime = createWorkerRuntime({ load: loadModel, generate });
const { port, generations } = workerRuntime;

// kokoro.web.js bundles its own Transformers.js, which downloads the model,
// tokenizer, and voices from hard-coded /resolve/main/ URLs through the
// global fetch and takes no revision option. Rewriting those URLs here is
// what pins every Kokoro download to KOKORO_MODEL_REVISION.
const workerScope = self as typeof self & { fetch?: typeof fetch };
if (typeof workerScope.fetch === "function") {
  workerScope.fetch = createRevisionPinnedFetch(
    workerScope.fetch.bind(workerScope),
    KOKORO_MODEL_ID,
    KOKORO_MODEL_REVISION,
  );
}

interface KokoroChunkUnit {
  text: string;
  start?: number;
  end?: number;
  pauseAfterSec: number;
  pauseKind: ChunkPauseKind;
  depth: number;
}

async function loadKokoroModule(): Promise<KokoroModule> {
  if (!kokoroModulePromise) {
    // Imported by URL rather than as "kokoro-js" so the bundler never rewrites
    // it; see KOKORO_WEB_MODULE_URL in vite.kokoroAssets.ts.
    kokoroModulePromise = import(/* @vite-ignore */ KOKORO_WEB_MODULE_URL) as Promise<KokoroModule>;
  }
  return kokoroModulePromise;
}

async function ensureKokoroCacheRevisions(): Promise<void> {
  if (typeof caches === "undefined") return;
  await ensureRevisionScopedCache(
    caches,
    KOKORO_VOICE_CACHE_NAME,
    KOKORO_VOICE_CACHE_REVISION_MARKER,
    KOKORO_MODEL_REVISION,
  );
  await ensureRevisionScopedCacheEntries(
    caches,
    KOKORO_TRANSFORMERS_CACHE_NAME,
    KOKORO_TRANSFORMERS_CACHE_REVISION_MARKER,
    KOKORO_MODEL_REVISION,
    (url) => url.includes(KOKORO_MODEL_ID) || url.includes(encodeURIComponent(KOKORO_MODEL_ID)),
  );
}

function listVoices(instance: KokoroTTSInstance): string[] {
  const dynamicVoices = (instance as unknown as { voices?: Record<string, unknown> }).voices;
  if (dynamicVoices && typeof dynamicVoices === "object") {
    const keys = Object.keys(dynamicVoices);
    if (keys.length > 0) return keys;
  }

  const result = instance.list_voices();
  if (Array.isArray(result) && result.length > 0) return result;

  return [...KOKORO_FALLBACK_VOICES];
}

function buildInferenceUnits(text: string): KokoroChunkUnit[] {
  // The same units and pauses the Reader previews, so highlighted boundaries
  // and the Creator pause settings match what is actually generated.
  return chunkForKokoroDetailed(text, { backend: activeBackend }).map((chunk) => ({
    text: chunk.text,
    start: chunk.start,
    end: chunk.end,
    pauseAfterSec: chunk.pauseAfterSec,
    pauseKind: chunk.pauseKind,
    depth: 0,
  }));
}

async function disposeKokoroModel(instance: KokoroTTSInstance | null): Promise<void> {
  // kokoro-js 1.2.1 exposes the Transformers model, not a wrapper dispose().
  const wrapper = instance as unknown as {
    dispose?: () => void | Promise<void>;
    model?: { dispose?: () => void | Promise<unknown> };
  } | null;
  const disposable = typeof wrapper?.dispose === "function" ? wrapper : wrapper?.model;
  if (typeof disposable?.dispose !== "function") return;
  try {
    await disposable.dispose();
  } catch (error) {
    console.warn("[kokoro] Failed to dispose model cleanly", error);
  }
}

async function warmupKokoroModel(instance: KokoroTTSInstance): Promise<void> {
  const availableVoices = listVoices(instance);
  const warmupVoice = resolveKokoroVoice(availableVoices[0] ?? "af_heart", availableVoices);
  if (!warmupVoice) return;
  await instance.generate("Warm up.", { voice: warmupVoice as KokoroVoiceId, speed: 1 });
}

/** Byte-weighted progress over the files a load on `backend` downloads. */
function createKokoroLoadProgress(backend: InferenceBackend): LoadProgress {
  const files = ["config.json", "tokenizer.json", "tokenizer_config.json", BACKEND_CONFIG[backend].modelFile];
  return createLoadProgress({
    report: (percent) => port.post({ type: "LOAD_PROGRESS", percent }),
    range: [0, DOWNLOAD_PROGRESS_MAX],
    expectedBytes: Object.fromEntries(files.map((file) => [file, LOAD_ASSET_SIZES[file].byteLength])),
  });
}

/**
 * Feeds Transformers.js progress events to the bar and the load watchdog:
 * every event is activity, and once every file that started downloading has
 * finished, only session creation remains and the settling budget applies.
 */
function createProgressListener(progress: LoadProgress, watchdog: LoadWatchdog): (info: unknown) => void {
  const started = new Set<string>();
  const finished = new Set<string>();
  return (info) => {
    watchdog.touch();
    progress.handleTransformersEvent(info);
    const { file, status } = (info ?? {}) as { file?: unknown; status?: unknown };
    if (typeof file !== "string") return;
    if (status === "initiate" || status === "progress") started.add(file);
    if (status === "done") finished.add(file);
    if (started.size > 0 && [...started].every((name) => finished.has(name))) watchdog.settle();
  };
}

async function loadKokoroOn(kokoroModule: KokoroModule, backend: InferenceBackend): Promise<KokoroTTSInstance> {
  configureKokoroOnnxRuntime(kokoroModule.env, KOKORO_ONNX_WASM_ASSETS, {
    backend,
    maxWasmThreads: MAX_WASM_THREADS,
  });
  const progress = createKokoroLoadProgress(backend);
  try {
    return await withLoadWatchdog<KokoroTTSInstance>(
      (watchdog) => kokoroModule.KokoroTTS.from_pretrained(KOKORO_MODEL_ID, {
        dtype: BACKEND_CONFIG[backend].dtype,
        device: backend,
        progress_callback: createProgressListener(progress, watchdog),
      }),
      {
        label: `Kokoro ${backend} load`,
        inactivityMs: KOKORO_LOAD_INACTIVITY_MS,
        settlingMs: KOKORO_LOAD_SETTLING_MS,
        disposeLate: disposeKokoroModel,
      },
    );
  } finally {
    // from_pretrained cannot be cancelled: an attempt the watchdog abandoned
    // keeps downloading, and its progress must not reach the host.
    progress.close();
  }
}

async function loadModel({ forceReload = false }: LoadMessage): Promise<void> {
  if (tts && activeBackend && !forceReload) {
    port.post({ type: "READY", voices, backend: activeBackend });
    return;
  }

  // Dropped before the first await, so a GENERATE that arrives during the
  // reload is refused instead of running on the model being released.
  const previousTts = tts;
  tts = null;
  activeBackend = null;
  voices = [];
  // The runtime superseded the running generation when a forced reload
  // arrived; never release the model under its in-flight inference.
  await generations.idle();
  await disposeKokoroModel(previousTts);

  port.post({ type: "LOAD_PROGRESS", percent: 0 });
  await ensureKokoroCacheRevisions();
  const kokoroModule = await loadKokoroModule();
  phonemize = typeof kokoroModule.phonemize === "function" ? kokoroModule.phonemize : null;
  if (!phonemize) {
    console.warn("[kokoro] phonemize is not exported; long passages may lose their end to truncation.");
  }
  const loaded = await loadWithBackendFallback<KokoroTTSInstance>({
    backends: BACKEND_ORDER,
    load: (backend) => loadKokoroOn(kokoroModule, backend),
    // Compiles the WebGPU shaders before READY instead of on the first chunk.
    warmUp: (instance, backend) => (backend === "webgpu" ? warmupKokoroModel(instance) : Promise.resolve()),
    dispose: disposeKokoroModel,
    onFallback: () => port.post({ type: "LOAD_PROGRESS", percent: 0 }),
    failureMessage: "Failed to load Kokoro model",
  });
  tts = loaded.instance;
  voices = listVoices(loaded.instance);
  activeBackend = loaded.backend;
  port.post({ type: "READY", voices, backend: activeBackend });
}

/** Splits a unit that failed to generate in two near its middle, for a retry. */
function splitForRetry(unit: KokoroChunkUnit): KokoroChunkUnit[] {
  if (unit.text.length < 40 || unit.depth >= 2) return [unit];
  const splitAt = findSplitNearMiddle(unit.text);
  if (splitAt === null) return [unit];

  // Units are trimmed ranges of the source text, so both parts keep exact offsets.
  const leftText = unit.text.slice(0, splitAt).trimEnd();
  const rightText = unit.text.slice(splitAt);
  const rightStart = unit.start !== undefined ? unit.start + splitAt : undefined;
  return [
    {
      text: leftText,
      start: unit.start,
      end: unit.start !== undefined ? unit.start + leftText.length : undefined,
      pauseAfterSec: 0.14,
      pauseKind: "comma",
      depth: unit.depth + 1,
    },
    {
      text: rightText,
      start: rightStart,
      end: unit.end,
      pauseAfterSec: unit.pauseAfterSec,
      pauseKind: unit.pauseKind,
      depth: unit.depth + 1,
    },
  ];
}

interface KokoroSynthesisOptions {
  voice: KokoroVoiceId;
  speed: number;
  tune(text: string): string;
}

/**
 * Synthesizes `text` without losing its end to Kokoro's context. kokoro-js's
 * generate() phonemizes, tokenizes with truncation, and runs the model; this
 * runs the same steps but tokenizes without truncation, and text whose
 * phonemes need more ids than the context holds is split near its middle
 * (see findSplitNearMiddle) until every part fits. Characters are a poor
 * proxy: digits and abbreviations expand into many phonemes. Returns the
 * parts' audio in order, or null once the generation is no longer current.
 */
async function synthesizeWithinContext(
  instance: KokoroTTSInstance,
  text: string,
  options: KokoroSynthesisOptions,
  ticket: GenerationTicket,
): Promise<KokoroRawAudio[] | null> {
  const { voice, speed } = options;
  const tunedText = options.tune(text);
  if (!phonemize) return [await instance.generate(tunedText, { voice, speed })];

  // The language kokoro-js derives from the voice: "a" (American) or "b" (British).
  const phonemes = await phonemize(tunedText, voice.at(0));
  if (!ticket.isCurrent()) return null;
  const { input_ids: inputIds } = (instance.tokenizer as unknown as KokoroTokenize)(phonemes, { truncation: false });
  const splitAt = (inputIds.dims.at(-1) ?? 0) > KOKORO_MAX_INPUT_IDS ? findSplitNearMiddle(text) : null;
  if (splitAt === null) return [await instance.generate_from_ids(inputIds, { voice, speed })];

  const left = await synthesizeWithinContext(instance, text.slice(0, splitAt).trimEnd(), options, ticket);
  if (!left || !ticket.isCurrent()) return null;
  const right = await synthesizeWithinContext(instance, text.slice(splitAt), options, ticket);
  return right && [...left, ...right];
}

async function generate(message: GenerateMessage, ticket: GenerationTicket): Promise<void> {
  const ttsInstance = tts;
  if (!ttsInstance) throw new Error("Model not loaded yet");

  const selectedVoice = resolveKokoroVoice(message.voice, voices);
  if (!selectedVoice) throw new Error("No Kokoro voices are available.");

  const normalizedSpeed = clampSpeed(message.speed);
  const units = buildInferenceUnits(message.text);
  if (units.length === 0) throw new Error("Input text is empty.");

  const pronunciationRules = message.pronunciationRules ?? [];
  const emphasisStrength = message.emphasisStrength ?? 0;
  const sentenceSpeedVariance = message.sentenceSpeedVariance ?? 0;
  const queue: KokoroChunkUnit[] = [...units];
  let emitted = 0;
  let firstFailure: { error: unknown } | null = null;
  let hasDynamicTotal = false;

  while (ticket.isCurrent() && queue.length > 0) {
    const unit = queue.shift()!;
    if (!unit.text.trim()) continue;

    try {
      const tune = (text: string) => tuneChunkText(text, pronunciationRules, emphasisStrength);
      // One speed for the whole unit, even when it is synthesized in parts.
      const unitSpeed = clampSpeed(resolveSentenceSpeed(normalizedSpeed, sentenceSpeedVariance, tune(unit.text)));
      const outputs = await synthesizeWithinContext(
        ttsInstance,
        unit.text,
        { voice: selectedVoice as KokoroVoiceId, speed: unitSpeed, tune },
        ticket,
      );
      if (!outputs || !ticket.isCurrent()) return;
      // Parts of a unit that outgrew the context play as one chunk, so the
      // chunk still matches the unit the Reader previews and highlights.
      const parts = outputs.map((output) => normalizeRawAudioOutput(
        output as unknown as Parameters<typeof normalizeRawAudioOutput>[0],
      ));
      const normalized = {
        audio: parts.length === 1 ? parts[0].audio : concatFloat32Arrays(parts.map((part) => part.audio)),
        samplingRate: parts[0].samplingRate,
      };
      const index = emitted + 1;
      const hasFollowing = queue.length > 0;
      emitAudioChunk(port, {
        generationId: message.generationId,
        audio: normalized.audio,
        samplingRate: normalized.samplingRate,
        text: unit.text,
        index,
        total: hasDynamicTotal ? 0 : index + queue.length,
        textStart: unit.start,
        textEnd: unit.end,
        pauseKind: unit.pauseKind,
        pauseSec: resolveChunkPauseSec({
          hasFollowing,
          pauseKind: unit.pauseKind,
          pauseAfterSec: unit.pauseAfterSec,
          pauseOverridesSec: message.pauseOverridesSec,
          finalPauseSec: message.finalPauseSec,
        }),
      });
      emitted = index;
    } catch (error) {
      if (!ticket.isCurrent()) return;
      const retryUnits = splitForRetry(unit);
      if (retryUnits.length > 1) {
        // Requeue split retries in order at the front; the chunk count is
        // no longer known up front.
        hasDynamicTotal = true;
        queue.unshift(...retryUnits);
        continue;
      }
      firstFailure ??= { error };
    }
  }

  if (!ticket.isCurrent()) return;
  if (firstFailure) {
    throw new Error(`Generation completed with skipped segments after ${emitted} chunks: ${errorMessage(firstFailure.error)}`);
  }
  if (emitted === 0) throw new Error("Model returned no audio chunks.");
  port.post({ type: "GENERATION_COMPLETE", ...generationMeta(message.generationId) });
}

self.onmessage = (event: MessageEvent<WorkerInMessage>) => {
  workerRuntime.handleMessage(event.data);
};
